PRAGMA foreign_keys = ON;
CREATE TABLE sites(id TEXT PRIMARY KEY, device TEXT NOT NULL, token_hash TEXT NOT NULL, accessed INTEGER NOT NULL, active TEXT);
CREATE INDEX sites_device ON sites(device);
CREATE TABLE deploys(id TEXT PRIMARY KEY, site TEXT NOT NULL REFERENCES sites(id) ON DELETE CASCADE, created INTEGER NOT NULL);
CREATE TABLE files(deploy TEXT NOT NULL REFERENCES deploys(id) ON DELETE CASCADE, path TEXT NOT NULL, sha TEXT NOT NULL, size INTEGER NOT NULL, PRIMARY KEY(deploy,path));
CREATE INDEX files_sha ON files(sha);
CREATE TABLE reports(id INTEGER PRIMARY KEY, site TEXT NOT NULL, reason TEXT NOT NULL, created INTEGER NOT NULL);
CREATE TABLE rate_limits(ip TEXT PRIMARY KEY, window INTEGER NOT NULL, count INTEGER NOT NULL);
