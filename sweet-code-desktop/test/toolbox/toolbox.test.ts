import test from "node:test";
import assert from "node:assert/strict";
import { promises as fs } from "node:fs";
import os from "node:os";
import path from "node:path";
import { ToolboxService, buildOpenUrl, emptyPrefs, validatePrefs, validateSite, validateUrl } from "../../src/main/toolbox/service.ts";
import { registerToolboxIpc } from "../../src/main/toolbox/ipc.ts";
const site = { id: "search", name: "Search", category: "global" as const, home: "https://example.com/", query: "https://example.com/search?q={q}&again={q}", login: "none" as const };
test("template replaces every placeholder and encodes questions without adding parameters", () => {
  const q = "中文 +&#?/={q}";
  const result = buildOpenUrl(site, q);
  assert.equal(result.url, "https://example.com/search?q=" + encodeURIComponent(q) + "&again=" + encodeURIComponent(q));
  assert.equal(result.copied, false);
  assert.deepEqual(buildOpenUrl(site), { url: site.home, copied: false });
  assert.deepEqual(buildOpenUrl({ ...site, query: undefined }, q), { url: site.home, copied: true });
});
test("rejects unsafe protocols, credentials, malformed templates and destination placeholders", () => {
  for (const url of ["file:///etc/passwd", "javascript:alert(1)", "data:text/html,x", "ftp://example.com", "https://user:pass@example.com", "https://example.com/\\x", "no-url"]) assert.throws(() => validateUrl(url));
  for (const query of ["https://example.com/no-placeholder", "file:///{q}", "https://{q}.example.com", "{q}://example.com"]) assert.throws(() => validateSite({ ...site, query }));
  assert.throws(() => buildOpenUrl(site, 42 as unknown as string));
});
test("custom sites validate, force custom category, reject duplicate IDs and invalid prefs", () => {
  const p = { ...emptyPrefs(), custom: [site], favorites: ["search", "search"], groups: [{ id: "group", name: "Group", sites: ["search"] }] };
  assert.equal(validatePrefs(p, []).custom[0].category, "custom");
  assert.deepEqual(validatePrefs(p, []).favorites, ["search"]);
  assert.throws(() => validatePrefs(p, [site]));
  assert.throws(() => validatePrefs({ ...p, custom: [site, site] }, []));
  assert.throws(() => validatePrefs({ ...p, hidden: "search" }, []));
  assert.throws(() => validatePrefs({ ...p, custom: [{ ...site, home: "file:///tmp" }] }, []));
  assert.throws(() => validateSite({ ...site, login: "secret" }));
});
test("manifest loading, prefs atomic writes/fallback, clipboard and IPC", async t => {
  const dir = await fs.mkdtemp(path.join(os.tmpdir(), "toolbox-"));
  t.after(() => fs.rm(dir, { recursive: true, force: true }));
  const manifest = path.join(dir, "sites.json");
  await fs.writeFile(manifest, JSON.stringify([site, { ...site, id: "paste", query: "" }, { ...site, id: "invalid", home: "file:///" }, site]));
  const copies: string[] = [];
  const service = new ToolboxService(manifest, dir, q => copies.push(q));
  assert.deepEqual(await service.prefs(), emptyPrefs());
  assert.equal((await service.sites()).length, 2);
  const prefs = { ...emptyPrefs(), custom: [{ ...site, id: "custom", query: undefined }], order: ["paste", "search"], hidden: ["search"] };
  await service.savePrefs(prefs);
  const reopened = new ToolboxService(manifest, dir, q => copies.push(q));
  assert.deepEqual((await reopened.prefs()).order, prefs.order);
  assert.equal((await reopened.sites()).length, 3);
  assert.deepEqual(await reopened.openUrl("paste", "你好"), { url: site.home, copied: true });
  assert.deepEqual(copies, ["你好"]);
  await reopened.openUrl("search", "question");
  await reopened.openUrl("paste", "");
  assert.equal(copies.length, 1);
  await assert.rejects(reopened.openUrl("unknown"));
  await assert.rejects(reopened.savePrefs({ ...prefs, custom: [{ ...site, id: "search" }] }));
  assert.deepEqual((await reopened.prefs()).order, prefs.order);
  await Promise.all([reopened.savePrefs({ ...prefs, favorites: ["search"] }), reopened.savePrefs({ ...prefs, favorites: ["paste"] })]);
  assert.deepEqual((await reopened.prefs()).favorites, ["paste"]);
  const handlers = new Map<string, (...args: any[]) => unknown>();
  registerToolboxIpc((channel, handler) => handlers.set(channel, handler), reopened);
  assert.equal(handlers.size, 4);
  assert.equal((await handlers.get("toolbox:sites")!(null) as unknown[]).length, 3);
  await fs.writeFile(path.join(dir, "toolbox.json"), "bad json");
  assert.deepEqual(await reopened.prefs(), emptyPrefs());
  await fs.writeFile(path.join(dir, "toolbox.json"), JSON.stringify({ ...prefs, hidden: [42] }));
  assert.deepEqual(await reopened.prefs(), emptyPrefs());
  await fs.writeFile(manifest, "bad json");
  assert.deepEqual(await reopened.sites(), []);
  await fs.rm(manifest);
  assert.deepEqual(await reopened.sites(), []);
});
